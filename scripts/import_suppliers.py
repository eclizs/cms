def clean_name(n):
    return (n or "").replace("`", " ").strip().rstrip(",").strip()


payload = {"suppliers": []}
for r in RAW:
    name = clean_name(r.get("NAMA SUPPLIER"))
    acc = (r.get("NOMOR REKENING") or "").strip()
    if not name or not acc:
        continue
    payload["suppliers"].append({
        "name": name,
        "alias": (r.get("ALIAS") or "").strip(),
        "bank": (r.get("BANK") or "").strip(),
        "account_number": acc,
        "contact": "",
    })

